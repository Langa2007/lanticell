package reload

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/lanticell/gateway-agent/internal/validator"
)

// RenderNginxConfig generates NGINX server blocks for all verified sites in the bundle.
func RenderNginxConfig(bundle validator.ConfigBundle) string {
	var b strings.Builder
	b.WriteString("# Auto-generated by lanticell gateway-agent. Do not edit manually.\n")
	b.WriteString(fmt.Sprintf("# Bundle version: %d\n\n", bundle.Version))

	for _, site := range bundle.Sites {
		b.WriteString("server {\n")
		b.WriteString("    listen 80;\n")
		b.WriteString(fmt.Sprintf("    server_name %s;\n\n", site.Domain))
		b.WriteString(fmt.Sprintf("    client_max_body_size %d;\n", site.MaxBodyBytes))
		b.WriteString("    limit_conn lanticell_conn 100;\n")
		b.WriteString("    limit_req zone=lanticell_req burst=100 nodelay;\n")
		wafMode := site.WAFMode
		if wafMode == "" {
			wafMode = "monitor"
		}
		b.WriteString(fmt.Sprintf("    # WAF mode: %s (CRS %s)\n", wafMode, site.CRSVersion))
		for _, ex := range site.WAFExclusions {
			b.WriteString(fmt.Sprintf("    # WAF exclusion: route=%s rule=%s\n", ex.RoutePrefix, ex.RuleID))
		}
		b.WriteString("\n")
		b.WriteString("    location / {\n")
		b.WriteString(fmt.Sprintf("        proxy_pass %s;\n", site.UpstreamURL))
		b.WriteString("        proxy_http_version 1.1;\n")
		b.WriteString("        proxy_set_header Host $host;\n")
		b.WriteString("        proxy_set_header X-Real-IP $remote_addr;\n")
		b.WriteString("        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;\n")
		b.WriteString("        proxy_set_header X-Forwarded-Proto $scheme;\n")
		b.WriteString("        proxy_set_header X-Request-ID $request_id;\n")
		b.WriteString(fmt.Sprintf("        proxy_set_header X-Lanticell-Origin-Secret \"%s\";\n", site.OriginSecret))
		b.WriteString(fmt.Sprintf("        proxy_connect_timeout %dms;\n", site.ConnectTimeoutMs))
		b.WriteString(fmt.Sprintf("        proxy_read_timeout %dms;\n", site.ReadTimeoutMs))
		b.WriteString("    }\n")
		b.WriteString("}\n\n")
	}
	return b.String()
}

// ApplyBundle validates, atomically writes the NGINX config, and persists last-known-good state.
// If validation fails, existing config and last-known-good state remain untouched.
func ApplyBundle(bundle validator.ConfigBundle, signingKey []byte, nginxConfDir, lastGoodDir string) error {
	if err := validator.VerifyAndValidate(bundle, signingKey); err != nil {
		return err
	}
	if err := os.MkdirAll(nginxConfDir, 0o755); err != nil {
		return err
	}
	if err := os.MkdirAll(lastGoodDir, 0o755); err != nil {
		return err
	}

	rendered := RenderNginxConfig(bundle)
	targetConf := filepath.Join(nginxConfDir, "lanticell-sites.conf")
	tmpConf := targetConf + ".tmp"
	if err := os.WriteFile(tmpConf, []byte(rendered), 0o644); err != nil {
		return err
	}
	if err := os.Rename(tmpConf, targetConf); err != nil {
		_ = os.Remove(tmpConf)
		return err
	}

	bundleBytes, err := json.MarshalIndent(bundle, "", "  ")
	if err != nil {
		return err
	}
	lastGoodFile := filepath.Join(lastGoodDir, "bundle.json")
	tmpGood := lastGoodFile + ".tmp"
	if err := os.WriteFile(tmpGood, bundleBytes, 0o600); err != nil {
		return err
	}
	return os.Rename(tmpGood, lastGoodFile)
}

// LoadLastGood loads the last known good bundle from disk (used during control-plane outages).
func LoadLastGood(lastGoodDir string) (validator.ConfigBundle, error) {
	var bundle validator.ConfigBundle
	data, err := os.ReadFile(filepath.Join(lastGoodDir, "bundle.json"))
	if err != nil {
		return bundle, err
	}
	if err := json.Unmarshal(data, &bundle); err != nil {
		return bundle, err
	}
	return bundle, nil
}
